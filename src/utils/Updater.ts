import * as path from 'node:path';
import { execFile, spawn } from 'node:child_process';
import { promisify } from 'node:util';
import { Client } from 'discord.js';
import { UpdateCommit, UpdateStatus } from '../shared/types';

// Updates the bot from GitHub from the panel: git pull, npm install (when dependencies changed),
// npm run build, then a restart through pm2. Also checks for new commits every few hours.

const execFileAsync = promisify(execFile);
const BOT_ROOT = path.resolve(__dirname, '..', '..');
const CHECK_INTERVAL = 6 * 60 * 60 * 1000;
const MAX_LOG_LINES = 600;
const FIELD = '\x1f';
const LOG_FORMAT = `--format=%H${FIELD}%s${FIELD}%an${FIELD}%at`;
// Regenerated by npm install; a local change here would only block the pull.
const GENERATED_FILES = new Set(['package-lock.json']);

const state: Omit<UpdateStatus, 'pm2'> = {
  gitAvailable: true,
  branch: null,
  current: null,
  behind: 0,
  commits: [],
  changedFiles: [],
  checkedAt: null,
  checkError: null,
  running: false,
  step: null,
  log: [],
  finishedAt: null,
  success: null
};

let checking: Promise<void> | null = null;
let timer: NodeJS.Timeout | null = null;

async function git(args: string[], timeout = 60_000): Promise<string> {
  const { stdout } = await execFileAsync('git', args, { cwd: BOT_ROOT, windowsHide: true, timeout, maxBuffer: 8 * 1024 * 1024 });
  // Only the end: `git status --porcelain` lines start with a meaningful space (" M file").
  return stdout.trimEnd();
}

function parseCommits(output: string): UpdateCommit[] {
  return output.split('\n').filter(Boolean).map(line => {
    const [hash, subject, author, time] = line.split(FIELD);
    return { hash, subject, author, date: Number(time) * 1000 };
  });
}

async function changedFiles(): Promise<string[]> {
  const output = await git(['status', '--porcelain', '--untracked-files=no']);
  return output.split('\n').filter(Boolean).map(line => line.slice(3).trim());
}

export function updateStatus(): UpdateStatus {
  return { ...state, log: [...state.log], pm2: process.env.pm_id !== undefined };
}

// Installed version, branch and changed files: local git only, no network.
async function readLocal(): Promise<boolean> {
  try {
    await git(['rev-parse', '--is-inside-work-tree']);
  } catch {
    state.gitAvailable = false;
    state.checkError = 'This folder is not a git checkout (or git is not installed), so the bot cannot update itself.';
    return false;
  }
  state.gitAvailable = true;
  state.branch = await git(['rev-parse', '--abbrev-ref', 'HEAD']);
  state.current = parseCommits(await git(['log', '-1', LOG_FORMAT]))[0] ?? null;
  state.changedFiles = await changedFiles();
  return true;
}

// The status with fresh local information (while no update or check is running).
export async function currentUpdateStatus(): Promise<UpdateStatus> {
  if (!state.running && !checking) await readLocal().catch(() => {});
  return updateStatus();
}

async function runCheck(client: Client): Promise<void> {
  if (!(await readLocal().catch(() => false))) {
    state.checkedAt = Date.now();
    return;
  }

  try {
    await git(['fetch', '--quiet'], 120_000);
    state.commits = parseCommits(await git(['log', 'HEAD..@{u}', LOG_FORMAT]));
    state.behind = state.commits.length;
    state.checkError = null;
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    state.checkError = /no upstream/i.test(message)
      ? `The branch "${state.branch}" doesn't track a branch on GitHub.`
      : `Could not reach GitHub: ${message.split('\n').find(line => line.trim()) ?? message}`;
  } finally {
    state.checkedAt = Date.now();
  }

  const newest = state.commits[0];
  if (newest) {
    const list = state.commits.slice(0, 10).map(c => `• ${c.subject}`).join('\n');
    void client.alerts.send('updates', `⬆️ ${state.behind} new ${state.behind === 1 ? 'update' : 'updates'} on GitHub`,
      `${list}${state.behind > 10 ? `\n…and ${state.behind - 10} more` : ''}\n\nInstall them in the panel under Settings → Updates.`,
      { key: `update:${newest.hash}`, cooldownMs: 365 * 24 * 60 * 60 * 1000 });
  }
}

export function checkForUpdates(client: Client): Promise<void> {
  // Two git commands at once trip over each other; a running update checks again when it's done.
  if (state.running) return Promise.resolve();
  checking ??= runCheck(client).finally(() => { checking = null; });
  return checking;
}

export function startUpdateChecks(client: Client): void {
  if (timer) return;
  setTimeout(() => void checkForUpdates(client), 2 * 60 * 1000);
  timer = setInterval(() => void checkForUpdates(client), CHECK_INTERVAL);
}

function addLog(line: string): void {
  const clean = line.replace(/\x1b\[[0-9;]*[A-Za-z]/g, '').trimEnd();
  if (!clean.trim()) return;
  state.log.push(clean);
  if (state.log.length > MAX_LOG_LINES) state.log.shift();
  console.log(`[update] ${clean}`);
}

// Runs a command and streams its output into the update log.
function run(command: string, args: string[]): Promise<void> {
  addLog(`$ ${command} ${args.join(' ')}`);
  return new Promise((resolve, reject) => {
    // npm is a .cmd script on Windows, which only starts through a shell. The arguments are fixed.
    const shell = command === 'npm' && process.platform === 'win32';
    // pm2 starts the bot with NODE_ENV=production. Passed on, it makes npm skip (and remove) the
    // devDependencies the build needs (TypeScript, Vite). The build sets its own mode.
    const env = { ...process.env };
    delete env.NODE_ENV;
    const child = spawn(command, args, { cwd: BOT_ROOT, env, windowsHide: true, shell, stdio: ['ignore', 'pipe', 'pipe'] });
    const forward = (data: Buffer) => data.toString().split(/\r?\n/).forEach(addLog);
    child.stdout.on('data', forward);
    child.stderr.on('data', forward);
    child.on('error', reject);
    child.on('exit', (code) => (code === 0 ? resolve() : reject(new Error(`${command} ${args[0]} failed with exit code ${code}`))));
  });
}

// `rebuild` installs and builds even without new commits (e.g. after a manual git pull or a failed build).
export function startUpdate(client: Client, options: { rebuild?: boolean } = {}): void {
  if (state.running) throw new Error('An update is already running.');
  if (!state.gitAvailable) throw new Error(state.checkError ?? 'git is not available.');

  Object.assign(state, { running: true, log: [], finishedAt: null, success: null, step: 'Preparing' });
  const pm2 = process.env.pm_id !== undefined;

  void (async () => {
    try {
      if (checking) await checking;
      const blocking = (await changedFiles()).filter(file => !GENERATED_FILES.has(file));
      if (blocking.length > 0) {
        throw new Error(`These files were changed on the server and would be overwritten: ${blocking.join(', ')}. Commit, stash or undo them first (git stash, or git checkout -- <file>).`);
      }

      state.step = 'Backing up the database';
      const backup = client.backups.create('before-update');
      addLog(`Database saved to data/backups/${backup.name}`);

      const before = await git(['rev-parse', 'HEAD']);
      for (const file of await changedFiles()) {
        addLog(`Resetting ${file} (it is regenerated by npm install)`);
        await git(['checkout', '--', file]);
      }

      state.step = 'Downloading the update';
      await run('git', ['fetch']);
      await run('git', ['merge', '--ff-only', '@{u}']);
      const after = await git(['rev-parse', 'HEAD']);

      const install = before !== after || !!options.rebuild;
      if (!install) {
        addLog('Already up to date.');
      } else {
        // Always, not only when package.json changed: a missing package (after a manual pull,
        // or devDependencies removed by an earlier production install) breaks the build otherwise.
        state.step = 'Installing dependencies';
        await run('npm', ['install', '--include=dev', '--no-audit', '--no-fund']);

        // The build first deletes dist/, so check the code before: a failing check keeps the running version intact.
        state.step = 'Checking the code';
        await run('npm', ['run', 'typecheck']);

        state.step = 'Building';
        await run('npm', ['run', 'build']);
      }

      state.success = true;
      state.step = !install ? 'Already up to date' : pm2 ? 'Restarting' : 'Done – restart the bot to finish';
      addLog(!install ? 'Nothing to install.' : pm2 ? 'Installed and built. Restarting the bot…' : 'Installed and built. The bot is not running under pm2: restart it yourself to use the new version.');
      state.commits = [];
      state.behind = 0;

      if (pm2 && install) setTimeout(() => process.exit(0), 1500);
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      const failedStep = state.step;
      state.success = false;
      addLog(`❌ ${message}`);
      state.step = 'Failed';
      void client.alerts.send('updates', '❌ The update failed', `The bot keeps running the version it had. It failed while "${failedStep}":\n\`\`\`${message.slice(0, 800)}\`\`\`\nSee Maintenance → Updates in the panel for the full log.`, { key: `update-failed:${Date.now()}`, cooldownMs: 0 });
    } finally {
      state.running = false;
      state.finishedAt = Date.now();
      void checkForUpdates(client);
    }
  })();
}
